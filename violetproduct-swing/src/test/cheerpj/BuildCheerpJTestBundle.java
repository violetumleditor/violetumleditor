import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.time.Instant;
import java.util.Base64;
import java.util.List;
import java.util.stream.Stream;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;

/**
 * Builds the bundle used by web/test.html to run the unpackaged application with CheerpJ from a
 * file:// URL. Browsers block fetch() on file:// pages, so CheerpJ cannot load classes or jars from
 * disk; a script tag, however, can load a .js file. This program writes every class path entry
 * (module target/classes directories zipped as jars, third-party jars as is) into one .js file as
 * base64. test.html then copies them into CheerpJ's /str/ filesystem and runs the app from there.
 *
 * Launched by the "cheerpj-test" Maven profile of violetproduct-swing (mvn compile -Pcheerpj-test).
 *
 * Usage: java BuildCheerpJTestBundle.java <output .js file> <class path>
 */
public class BuildCheerpJTestBundle
{

    public static void main(String[] args) throws IOException
    {
        if (args.length != 2)
        {
            System.err.println("Usage: java BuildCheerpJTestBundle.java <output .js file> <class path>");
            System.exit(1);
        }
        Path output = Paths.get(args[0]);
        Files.createDirectories(output.getParent());
        long totalBytes = 0;
        try (Writer out = Files.newBufferedWriter(output, StandardCharsets.UTF_8))
        {
            out.write("// Generated by BuildCheerpJTestBundle.java on " + Instant.now() + " - do not edit\n");
            out.write("window.VIOLET_TEST_BUNDLE = [\n");
            for (String entry : args[1].split(java.io.File.pathSeparator))
            {
                Path path = Paths.get(entry);
                byte[] jar;
                String name;
                if (Files.isDirectory(path))
                {
                    // <module>/target/classes -> <module>.jar
                    jar = zipDirectory(path);
                    name = path.getParent().getParent().getFileName() + ".jar";
                }
                else if (entry.endsWith(".jar") && Files.isRegularFile(path))
                {
                    jar = Files.readAllBytes(path);
                    name = path.getFileName().toString();
                }
                else
                {
                    continue;
                }
                totalBytes += jar.length;
                out.write("  { name: \"" + name + "\", data: \"" + Base64.getEncoder().encodeToString(jar) + "\" },\n");
                System.out.println("[cheerpj-test] " + name + " (" + jar.length / 1024 + " KB)");
            }
            out.write("];\n");
        }
        System.out.println("[cheerpj-test] Bundle written to " + output + " (" + totalBytes / 1024 + " KB of jars)");
    }

    private static byte[] zipDirectory(Path directory) throws IOException
    {
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        List<Path> files;
        try (Stream<Path> walk = Files.walk(directory))
        {
            files = walk.filter(Files::isRegularFile).sorted().toList();
        }
        try (ZipOutputStream zip = new ZipOutputStream(bytes))
        {
            for (Path file : files)
            {
                zip.putNextEntry(new ZipEntry(directory.relativize(file).toString().replace('\\', '/')));
                Files.copy(file, zip);
                zip.closeEntry();
            }
        }
        return bytes.toByteArray();
    }
}
